"""review_family.py — the teacher's switch for exception reasons (Phase 3 M10).

Run from the project folder:

  python tools/review_family.py                     list every family: stat,
                                                    pairs, how many reviewed
  python tools/review_family.py ie-half-filled-p    show that family's reason,
                                                    any per-pair overrides in
                                                    it, and every pair; then
                                                    type yes to mark them all
                                                    reviewed
  python tools/review_family.py ie-half-filled-p --unreview
                                                    take the approval back
  python tools/review_family.py --report            write data/EXCEPTION_FAMILIES.md,
                                                    every family's text and
                                                    pairs, for reading (it
                                                    changes no flags)

This is the ONLY tool that sets "reviewed": true in docs/data/exceptions.json
(project rule 7: Claude drafts, the teacher flips the flag). Claude never
runs it. A later rebuild keeps the flag only while the reason text is
unchanged, so editing a reason means reviewing it again.

Only the standard library is used, so the system Python runs it.
"""

import json
import sys
from collections import Counter, OrderedDict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
EXCEPTIONS = ROOT / "docs" / "data" / "exceptions.json"
REASONS = ROOT / "tools" / "exception_reasons.json"
REPORT = ROOT / "data" / "EXCEPTION_FAMILIES.md"


def load():
    if not EXCEPTIONS.exists():
        sys.exit(f"{EXCEPTIONS} does not exist. Run: node tools/build_exceptions.mjs")
    exceptions = json.loads(EXCEPTIONS.read_text(encoding="utf-8"))
    reasons = json.loads(REASONS.read_text(encoding="utf-8"))
    missing = [i for i, x in enumerate(exceptions) if not x.get("family")]
    if missing:
        sys.exit(f"exceptions.json entries {missing[:5]}... have no family. "
                 "Rebuild with: node tools/build_exceptions.mjs")
    return exceptions, reasons["families"]


def list_families(exceptions, families):
    total = Counter(x["family"] for x in exceptions)
    done = Counter(x["family"] for x in exceptions if x["reviewed"])
    print(f"{'family':32} {'stat':16} {'pairs':>5} {'reviewed':>8}  label")
    for name, f in families.items():
        flag = "  (lower confidence)" if f.get("confidence") == "lower" else ""
        print(f"{name:32} {f['stat']:16} {total[name]:5} {done[name]:8}  {f['label']}{flag}")
    print(f"\n{sum(done.values())} of {len(exceptions)} pairs reviewed.")


def show_family(name, exceptions, families):
    f = families[name]
    members = [x for x in exceptions if x["family"] == name]
    print(f"Family:  {name}  ({f['label']})")
    print(f"Stat:    {f['stat']}    Pairs: {len(members)}")
    if f.get("confidence") == "lower":
        print("Note:    Claude marked this draft LOWER confidence; read it closely.")
    # Every distinct text a student could see from this family.
    texts = OrderedDict()
    for x in members:
        texts.setdefault(x["reason"], []).append(f"{x['a']}/{x['b']}")
    for i, (text, pairs) in enumerate(texts.items(), 1):
        print(f"\nText {i} of {len(texts)}: shown for {len(pairs)} pair(s): {', '.join(pairs)}")
        print(f"  {text}")
    return members


def write_report(exceptions, families):
    """Every family, its text(s) and its pairs, as one Markdown page."""
    total = Counter(x["family"] for x in exceptions)
    done = Counter(x["family"] for x in exceptions if x["reviewed"])
    lines = ["# Exception families - for review",
             "",
             "Generated by `python tools/review_family.py --report` from "
             "docs/data/exceptions.json and tools/exception_reasons.json. Every "
             "reason is a DRAFT from Claude's training knowledge, not checked "
             "against a source. Approve a family with "
             "`python tools/review_family.py <family>`.",
             "",
             f"**{sum(done.values())} of {len(exceptions)} pairs reviewed.**",
             "",
             "| Family | Stat | Pairs | Reviewed | Confidence |",
             "|---|---|---|---|---|"]
    for name, f in families.items():
        lines.append(f"| `{name}` | {f['stat']} | {total[name]} | {done[name]} | "
                     f"{f.get('confidence', 'normal')} |")
    for name, f in families.items():
        members = [x for x in exceptions if x["family"] == name]
        lines += ["", f"## `{name}` - {f['label']}", "",
                  f"Stat `{f['stat']}`, {len(members)} pair(s), "
                  f"{done[name]} reviewed"
                  + (". **Lower-confidence draft.**" if f.get("confidence") == "lower" else ".")]
        texts = OrderedDict()
        for x in members:
            texts.setdefault(x["reason"], []).append(
                f"{x['a']}/{x['b']} (trend said {x['predicted']}, data says {x['actual']})")
        for text, pairs in texts.items():
            lines += ["", f"> {text}", "", "Shown for: " + "; ".join(pairs) + "."]
    REPORT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {REPORT.relative_to(ROOT)}")


def main(argv):
    exceptions, families = load()
    if argv == ["--report"]:
        write_report(exceptions, families)
        return
    if not argv:
        list_families(exceptions, families)
        return
    name = argv[0]
    if name not in families:
        sys.exit(f'No family named "{name}". Run with no arguments to list them.')
    unreview = "--unreview" in argv[1:]
    members = show_family(name, exceptions, families)
    verb = "UN-review" if unreview else "mark REVIEWED"
    answer = input(f"\nType yes to {verb} all {len(members)} pair(s) in {name}: ").strip().lower()
    if answer != "yes":
        print("Nothing changed.")
        return
    for x in exceptions:
        if x["family"] == name:
            x["reviewed"] = not unreview
    # Same layout the build script writes, so --check still passes.
    EXCEPTIONS.write_text(json.dumps(exceptions, indent=1, ensure_ascii=False) + "\n",
                          encoding="utf-8")
    done = sum(1 for x in exceptions if x["reviewed"])
    print(f"Done. {done} of {len(exceptions)} pairs are now reviewed. "
          "Commit docs/data/exceptions.json to publish.")


if __name__ == "__main__":
    main(sys.argv[1:])
