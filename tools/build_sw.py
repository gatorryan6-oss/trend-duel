"""build_sw.py — write the version and file list into docs/sw.js (Phase 4).

Run:  python tools/build_sw.py            rewrite the generated block
      python tools/build_sw.py --check    exit 1 if the block is stale
      python tools/build_sw.py --kill     EMERGENCY: write the kill switch
      python tools/build_sw.py --restore  bring the real worker back after --kill

The service worker (docs/sw.js) keeps an offline copy of the whole site. It
only trusts a file whose SHA-256 matches the list written here, and it only
switches to a new version when every file matches. This script is the one
place that list comes from.

The hash rule (Phase 4 kickoff §2), used by this script, by sw.js and by the
tests alike: SHA-256 of the file's bytes after turning CRLF into LF, in hex.
That way a Windows checkout and the file GitHub Pages serves give the same
hash.

VERSION is the first 7 hex characters of the SHA-256 of the sorted
"path:hash" lines, so it changes exactly when some file's content changes.

Standard library only, so the system Python runs it. Any change under docs/
needs a rerun; the invariant tests run --check, so a forgotten rerun fails
loudly.
"""

import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
SW = DOCS / "sw.js"
BEGIN = "// --- BEGIN GENERATED by tools/build_sw.py: do not edit by hand ---"
END = "// --- END GENERATED ---"

# The kill switch (Phase 4 M13): a worker that removes the offline copy from
# every device. On its next visit a device installs it; it takes over at once
# (the one designed exception to "never skipWaiting on its own"), deletes
# every trend-duel-* cache and unregisters itself. It has no fetch handler, so
# everything loads from the network exactly as before Phase 4. --check accepts
# it only byte-for-byte, and says loudly that it is in place.
KILL_MARKER = "// KILL SWITCH written by tools/build_sw.py --kill"
KILL_TEXT = KILL_MARKER + """
// The offline copy is OFF on every device that visits. To turn it back on:
//   python tools/build_sw.py --restore   then commit and push.
self.addEventListener("install", (event) => {
  event.waitUntil(self.skipWaiting());
});
self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const key of await caches.keys()) {
      if (key.startsWith("trend-duel-")) await caches.delete(key);
    }
    await self.registration.unregister();
  })());
});
"""


def content_hash(data: bytes) -> str:
    """The one hash rule: SHA-256 of the bytes with CRLF turned into LF."""
    return hashlib.sha256(data.replace(b"\r\n", b"\n")).hexdigest()


def site_files():
    """Every file under docs/ except sw.js itself, as sorted POSIX paths."""
    return sorted(p.relative_to(DOCS).as_posix() for p in DOCS.rglob("*")
                  if p.is_file() and p != SW)


def manifest():
    files = {path: content_hash((DOCS / path).read_bytes()) for path in site_files()}
    lines = "\n".join(f"{path}:{h}" for path, h in sorted(files.items()))
    version = hashlib.sha256(lines.encode("utf-8")).hexdigest()[:7]
    return version, files


def block(version, files):
    body = json.dumps(files, indent=2)
    return f'{BEGIN}\nconst VERSION = "{version}";\nconst FILES = {body};\n{END}'


def rewritten(text, new_block):
    """sw.js with its generated block replaced. Refuses a file without markers."""
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        sys.exit(f"{SW.relative_to(ROOT)} must contain the BEGIN and END marker lines exactly once.")
    start = text.index(BEGIN)
    stop = text.index(END) + len(END)
    return text[:start] + new_block + text[stop:]


def restore():
    """The newest committed sw.js that is the real worker (has the BEGIN
    marker), with its block rebuilt for the files on disk now."""
    log = subprocess.run(["git", "log", "--format=%H", "--", "docs/sw.js"], cwd=ROOT,
                         capture_output=True, text=True, check=True).stdout.split()
    for commit in log:
        text = subprocess.run(["git", "show", f"{commit}:docs/sw.js"], cwd=ROOT,
                              capture_output=True, text=True, encoding="utf-8",
                              check=True).stdout
        if BEGIN in text and KILL_MARKER not in text:
            return commit[:7], text
    sys.exit("No commit in git history has a real docs/sw.js to restore.")


def main(argv):
    if not SW.exists():
        sys.exit(f"{SW.relative_to(ROOT)} does not exist.")
    if "--kill" in argv:
        # --restore brings back the last COMMITTED worker, so uncommitted
        # edits to sw.js would be lost for good. Refuse rather than lose them.
        dirty = subprocess.run(["git", "diff", "--quiet", "HEAD", "--", "docs/sw.js"], cwd=ROOT)
        if dirty.returncode != 0:
            sys.exit("docs/sw.js has uncommitted changes; --restore could not bring them back. "
                     "Commit them first, then run --kill.")
        SW.write_text(KILL_TEXT, encoding="utf-8", newline="\n")
        print("wrote the KILL SWITCH to docs/sw.js. Commit and push it to switch the offline "
              "copy off everywhere; python tools/build_sw.py --restore undoes it.")
        return
    version, files = manifest()
    current = SW.read_text(encoding="utf-8")
    if "--restore" in argv:
        if KILL_MARKER not in current:
            sys.exit("docs/sw.js is not the kill switch; nothing to restore.")
        commit, current = restore()
        SW.write_text(rewritten(current, block(version, files)), encoding="utf-8", newline="\n")
        print(f"restored the worker from commit {commit}: version {version}, {len(files)} files. "
              "Commit and push it.")
        return
    if KILL_MARKER in current:
        if current != KILL_TEXT:
            sys.exit("docs/sw.js says it is the kill switch but differs from what --kill writes. "
                     "Run: python tools/build_sw.py --kill  (or --restore)")
        if "--check" in argv:
            print("WARNING: docs/sw.js is the KILL SWITCH -- the offline copy is OFF on every "
                  "device. Undo with: python tools/build_sw.py --restore")
            return
        sys.exit("docs/sw.js is the kill switch. Run: python tools/build_sw.py --restore")
    updated = rewritten(current, block(version, files))
    if "--check" in argv:
        if updated != current:
            sys.exit(f"docs/sw.js is STALE: the files under docs/ are now version {version}. "
                     "Run: python tools/build_sw.py")
        print(f"docs/sw.js is current: version {version}, {len(files)} files.")
        return
    SW.write_text(updated, encoding="utf-8", newline="\n")
    print(f"wrote docs/sw.js: version {version}, {len(files)} files.")


if __name__ == "__main__":
    main(sys.argv[1:])
